import random  # Подключает стандартный модуль Python для работы со случайными числами
list = random.sample(range(0, 1000001), 100)  # Случайным образом достает из диапазона от 0 до 1 000 000 ровно 100 уникальных чисел без повторений
list.sort()  # Сортирует полученный список по возрастанию, так как бинарный поиск работает только с отсортированными данными
print(list)  # Выводит весь сгенерированный список на экран, чтобы мы знали, какие числа можно искать
a = int(input("введите число"))  # Считывает строку, которую ввел пользователь, превращает её в целое число и сохраняет в переменную (искомое число)
b = -1  # Создает переменную для хранения индекса найденного числа в линейном поиске. Значение -1 означает, что число пока не найдено
c = 0  # Создает счетчик сравнений для линейного поиска, изначально он равен нулю
for i in range(len(list)):  # Запускает цикл, который по очереди перебирает все индексы списка от 0 до 99
    c += 1  # Увеличивает счетчик сравнений на 1 при каждом шаге цикла
    if list[i] == a:  # Проверяет, равен ли текущий элемент списка искомому числу
        b = i  # Если числа совпали, сохраняет текущий индекс i в переменную b
        break  # Прерывает выполнение цикла for, так как число уже найдено и дальше искать нет смысла
print("Линейный поиск")  # Печатает заголовок, чтобы было понятно, какой алгоритм выводит данные
if b != -1:  # Проверяет, изменился ли индекс. Если он не равен -1, значит, число успешно нашли
    print(b)  # Выводит индекс найденного элемента в списке
    print(c)  # Выводит итоговое количество сравнений, которое сделал линейный поиск
else:  # Если индекс так и остался равен -1 (числа в списке не оказалось)
    print("Элемент не найден")  # Выводит сообщение о том, что поиск не получился
d = -1  # Создает переменную для индекса бинарного поиска (аналогично -1, пока не найдено)
e = 0  # Создает счетчик сравнений для бинарного поиска
low = 0  # Задает начальную левую границу поиска (самый первый индекс в списке)
high = len(list) - 1  # Задает начальную правую границу поиска (самый последний индекс в списке)

while low <= high:  # Запускает цикл, который работает до тех пор, пока левая граница не перешагнет правую 
    e += 1  # Увеличивает счетчик сравнений бинарного поиска на 1 при каждом делении списка
    mid = (low + high) // 2  # Находит индекс элемента ровно посередине между текущими границами low и high 
    if list[mid] == a:  # Проверяет, равен ли средний элемент искомому числу
        d = mid  # Если угадали, сохраняет индекс середины в переменную d
        break  # Прерывает цикл while, так как элемент найден
    elif list[mid] < a:  # Если число в середине меньше, чем то, что мы ищем, значит, нужный элемент находится в правой половине
        low = mid + 1  # Сдвигает левую границу вправо, отсекая левую (ненужную) половину списка
    else:  # Если число в середине оказалось больше, чем то, что мы ищем, значит, нужный элемент находится в левой половине
        high = mid - 1  # Сдвигает правую границу влево, отсекая правую половину списка
print("Бинарный поиск")  # Печатает заголовок для результатов бинарного поиска
if d != -1:  # Проверяет, нашли ли мы элемент бинарным поиском
    print(d)  # Выводит индекс найденного элемента
    print(e)  # Выводит количество сравнений 
else:  # Если элемент так и не был найден
    print("Элемент не найден")  # Выводит сообщение о том, что элемента в списке нет